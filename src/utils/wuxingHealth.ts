/**
 * 五行养护建议（**必须按性别分档**）。
 *
 * 「肾主藏精、节欲保精」是男性养生语境；女性以血为本、重天癸，
 * 把「节欲保精」印在女命盘上是硬错，不是措辞问题。
 * 未知性别时走中性表述，**宁可不分档也不要默认男命**。
 */
export function wxHealthAdvice(wx: string, gender?: string): string {
  if (wx === '水') {
    if (gender === 'male') return '肾主藏精——房事有节、不憋尿、冬季注意腰腹保暖';
    if (gender === 'female') return '肾与内分泌宜温养——少熬夜、腰腹与脚踝保暖、经期忌生冷';
    return '肾与内分泌宜温养——不熬夜、不憋尿、腰腹与脚踝保暖、少生冷';
  }
  return WX_ADVICE_NEUTRAL[wx] || '';
}
