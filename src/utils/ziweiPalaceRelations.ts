  子女: ['交友', '父母'], 财帛: ['命宫', '官禄'], 疾厄: ['兄弟', '田宅'],
  迁移: ['夫妻', '福德'], 交友: ['子女', '父母'], 官禄: ['财帛', '命宫'],
  田宅: ['疾厄', '兄弟'], 福德: ['迁移', '夫妻'], 父母: ['子女', '交友'],
