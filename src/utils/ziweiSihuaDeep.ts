/**
 * 生成某宫的四化深度解读。
 * 宫内有生年四化优先取之；否则取自化星；两者皆无返回 null。
 */
export function generateSihuaDeepReading(gong: {
  name: string;
  majorStars?: { name: string; sihua?: string | null; sihuaSelf?: string | null }[];
  minorStarDetails?: { name: string; sihua?: string | null; sihuaSelf?: string | null }[];
}): SihuaDeepReading | null {
  const majors = gong.majorStars || [];
  const minors = gong.minorStarDetails || [];
  const ytStar = majors.find((s) => s.sihua) || minors.find((s) => s.sihua);
  const stStar = majors.find((s) => s.sihuaSelf) || minors.find((s) => s.sihuaSelf);
  const target = ytStar || stStar;
  if (!target) return null;

  const gongName = gong.name;
  const sihua = ytStar?.sihua || null;
  const self = stStar?.sihuaSelf || null;
  const sections: SihuaDeepSection[] = [];

  // 第1段：宫位领域 + 真实处境
  if (sihua === '忌') {
    sections.push({
      heading: `真实的处境（化忌的功课）`,
      text: `${GONG_DOMAIN[gongName]}${target.name}坐在这里，${STAR_NATURE[target.name] || ''}——而化忌让这份特质走向了深处：${GONG_JI_PAIN[gongName]}`,
    });
  } else if (sihua) {
    sections.push({
      heading: `天给的配置（化${sihua}的${sihua === '禄' ? '甜' : sihua === '权' ? '权柄' : '体面'}）`,
      text: `${GONG_DOMAIN[gongName]}${target.name}坐在这里，${STAR_NATURE[target.name] || ''}。${SIHUA_FLAVOR[sihua]}`,
    });
  } else {
    // 仅自化
    sections.push({
      heading: `这个宫位的底色`,
      text: `${GONG_DOMAIN[gongName]}${target.name}坐在这里，${STAR_NATURE[target.name] || ''}。自化是宫内能量的向外泄发——它定义了你在这个领域的"惯性输出方式"。`,
    });
  }

  // 第2段：自化（若有）
  if (self && self !== sihua) {
    const headingMap: Record<string, string> = {
      '科': sihua === '忌' ? '体面的面具（自化科的救）' : '向外的体面（自化科）',
      '禄': '向外的甜（自化禄）',
      '权': '向外的强（自化权）',
      '忌': '向外的火（自化忌）',
    };
    sections.push({ heading: headingMap[self] || `自化${self}`, text: SELF_HUA[self] });
  } else if (self && self === sihua) {
    sections.push({
      heading: `生年化${sihua}再自化${self}（叠化）`,
      text: `同一颗星既受生年化${sihua}、又自化${self}——这个领域的能量被反复"过手"，得而复失、失而复得的感受会比别人强烈一倍。起伏不是惩罚，是让你练"拿得起放得下"。`,
    });
  }

  // 第3段：核心矛盾
  if (sihua === '忌' && self && CONFLICT_WITH_SELF['忌'][self] && self !== '忌') {
    sections.push({ heading: '最致命的矛盾（虚实对决）', text: CONFLICT_WITH_SELF['忌'][self] });
  } else if (sihua === '忌' && self === '忌') {
    sections.push({ heading: '最致命的矛盾（双重执念）', text: CONFLICT_WITH_SELF['忌']['忌'] });
  } else if (sihua) {
    sections.push({
      heading: '需要注意的暗面',
      text: `化${sihua}坐${gongName}是"体用分明"的配置——先天的能量在这个领域持续显化。${PLAIN_ADVICE[sihua]}`,
    });
  } else if (self) {
    sections.push({
      heading: '需要注意的暗面',
      text: `自化的能量是"漏"的——不存不留、随来随去。要刻意建立"留存机制"：化禄设储蓄纪律、化权留缓冲时间、化科少立人设、化忌先写再说。把泄出去的能量，一点点收回来。`,
    });
  }

  // 第4段：健康与运势
  const health = STAR_HEALTH[target.name];
  if (sihua === '忌') {
    const bodyLink = (gongName === '福德' || gongName === '疾厄')
      ? `${gongName}宫与身体直接相连，化忌在此`
      : `${gongName}宫的郁结会间接影响身体——`;
    const selfNote = self
      ? `而自化${self}意味着这些不适容易被你藏在体面之下——比如忍着病痛去应酬、去工作，只为保全大局和面子。`
      : '别用"忙"来麻痹信号，定期体检、按时吃饭睡觉，是这个宫位最实在的开运方式。';
    sections.push({
      heading: '健康与运势的直接影响',
      text: `${bodyLink}容易因过度思虑或长期焦虑引发${health || '身心失衡'}。${selfNote}`,
    });
  } else {
    sections.push({
      heading: '健康与运势',
      text: `这个配置整体偏向"给"而非"耗"，但要注意${health || '身心平衡'}——顺风局最容易忽略身体，把作息当纪律，好运才守得住。`,
    });
  }

  return { gongName, starName: target.name, sihua, sihuaSelf: self, sections };
}

/** 生成全部十二宫中"有四化故事可讲"的深度解读 */
export function getAllSihuaDeepReadings(gongData: any[]): SihuaDeepReading[] {
  const out: SihuaDeepReading[] = [];
  const GONG_ORDER = ['命宫', '兄弟', '夫妻', '子女', '财帛', '疾厄', '迁移', '交友', '官禄', '田宅', '福德', '父母'];
  for (const name of GONG_ORDER) {
    const g = gongData.find((x) => x.name === name);
    if (!g) continue;
    const r = generateSihuaDeepReading(g);
    if (r) out.push(r);
  }
  return out;
}
