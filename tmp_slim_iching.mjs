function manualQiGua(input) {
  const cleaned = input.replace(/\s/g, "");
  if (cleaned.length !== 6) {
    throw new Error(`爻值字符串长度必须为6，当前长度: ${cleaned.length}`);
  }
  for (const char of cleaned) {
    if (!["6", "7", "8", "9"].includes(char)) {
      throw new Error(`无效的爻值: ${char}，必须是 6/7/8/9`);
    }
  }
  return cleaned;
}
